'use client';

import React from 'react';
import { Sparkles, Wand2, Search, Image as ImageIcon, Link2, Move, RefreshCw, Check, X } from 'lucide-react';
import { CURATED_COVER_PRESETS } from './constants';
import { useI18n } from '@/lib/i18n';

interface DeckCoverStepProps {
  coverMode: 'auto' | 'presets' | 'search' | 'custom';
  setCoverMode: (mode: 'auto' | 'presets' | 'search' | 'custom') => void;
  coverBannerRef: React.RefObject<HTMLDivElement | null>;
  setIsDraggingCover: (dragging: boolean) => void;
  coverDragStartRef: React.MutableRefObject<{ mouseX: number; mouseY: number; startPosX: number; startPosY: number } | null>;
  coverPosX: number;
  coverPosY: number;
  setCoverPosX: (x: number) => void;
  setCoverPosY: (y: number) => void;
  coverZoom: number;
  setCoverZoom: (zoom: number) => void;
  isDraggingCover: boolean;
  effectiveCoverUrl: string;
  aiDerivedTopic: string;
  targetLangName: string;
  isSearchingCovers: boolean;
  deckName: string;
  description: string;
  suggestedCovers: Array<{ id: string; url: string; title: string; photographer?: string }>;
  setSelectedCoverImage: (url: string) => void;
  coverSearchQuery: string;
  setCoverSearchQuery: (q: string) => void;
  handleSearchManualCovers: (q: string) => void;
  isSearchingManual: boolean;
  searchResults: Array<{ id: string; url: string; title: string; photographer?: string }>;
  customCoverInput: string;
  setCustomCoverInput: (url: string) => void;
  onRefreshAutoCover: () => void;
}

export function DeckCoverStep({
  coverMode,
  setCoverMode,
  coverBannerRef,
  setIsDraggingCover,
  coverDragStartRef,
  coverPosX,
  coverPosY,
  setCoverPosX,
  setCoverPosY,
  coverZoom,
  setCoverZoom,
  isDraggingCover,
  effectiveCoverUrl,
  aiDerivedTopic,
  targetLangName,
  isSearchingCovers,
  deckName,
  description,
  suggestedCovers,
  setSelectedCoverImage,
  coverSearchQuery,
  setCoverSearchQuery,
  handleSearchManualCovers,
  isSearchingManual,
  searchResults,
  customCoverInput,
  setCustomCoverInput,
  onRefreshAutoCover,
}: DeckCoverStepProps) {
  const { t } = useI18n();

  return (
    <div className="bg-white dark:bg-[#1f1f1f] rounded-3xl p-6 sm:p-7 shadow-xs border border-slate-100 dark:border-[#2e2e2e] space-y-5">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div className="flex items-center gap-3">
          <div className="w-7 h-7 rounded-full text-white bg-accent-primary font-bold text-xs flex items-center justify-center shrink-0">
            3
          </div>
          <div>
            <div className="flex items-center gap-2">
              <h2 className="text-sm sm:text-base font-bold text-[#1e293b] dark:text-white">{t('deckCoverImage')}</h2>
              <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[10px] font-bold bg-amber-500/10 text-amber-600 dark:text-amber-400 border border-amber-500/20">
                <Sparkles className="w-3 h-3" />
                {t('intelligent')}
              </span>
            </div>
            <p className="text-xs text-slate-500 dark:text-slate-400">
              {t('deckCoverDesc')}
            </p>
          </div>
        </div>

        {/* Mode Selector Tabs */}
        <div className="flex items-center gap-1 p-1 bg-slate-100 dark:bg-[#282828] rounded-xl self-start sm:self-auto flex-wrap">
          <button
            type="button"
            onClick={() => setCoverMode('auto')}
            className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-all flex items-center gap-1.5 cursor-pointer ${
              coverMode === 'auto'
                ? 'bg-white dark:bg-[#1f1f1f] text-slate-800 dark:text-white shadow-xs font-bold'
                : 'text-slate-500 dark:text-slate-400 hover:text-slate-800 dark:hover:text-white'
            }`}
          >
            <Wand2 className="w-3.5 h-3.5 text-accent-primary" />
            <span>{t('autoGenerated')}</span>
          </button>

          <button
            type="button"
            onClick={() => {
              setCoverMode('search');
              if (!coverSearchQuery && (aiDerivedTopic || targetLangName)) {
                const initialQ = aiDerivedTopic || targetLangName;
                setCoverSearchQuery(initialQ);
                handleSearchManualCovers(initialQ);
              }
            }}
            className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-all flex items-center gap-1.5 cursor-pointer ${
              coverMode === 'search'
                ? 'bg-white dark:bg-[#1f1f1f] text-slate-800 dark:text-white shadow-xs font-bold'
                : 'text-slate-500 dark:text-slate-400 hover:text-slate-800 dark:hover:text-white'
            }`}
          >
            <Search className="w-3.5 h-3.5 text-accent-primary" />
            <span>{t('imageSearch')}</span>
          </button>

          <button
            type="button"
            onClick={() => setCoverMode('presets')}
            className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-all flex items-center gap-1.5 cursor-pointer ${
              coverMode === 'presets'
                ? 'bg-white dark:bg-[#1f1f1f] text-slate-800 dark:text-white shadow-xs font-bold'
                : 'text-slate-500 dark:text-slate-400 hover:text-slate-800 dark:hover:text-white'
            }`}
          >
            <ImageIcon className="w-3.5 h-3.5" />
            <span>{t('curatedPresets')}</span>
          </button>

          <button
            type="button"
            onClick={() => setCoverMode('custom')}
            className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-all flex items-center gap-1.5 cursor-pointer ${
              coverMode === 'custom'
                ? 'bg-white dark:bg-[#1f1f1f] text-slate-800 dark:text-white shadow-xs font-bold'
                : 'text-slate-500 dark:text-slate-400 hover:text-slate-800 dark:hover:text-white'
            }`}
          >
            <Link2 className="w-3.5 h-3.5" />
            <span>{t('customUrl')}</span>
          </button>
        </div>
      </div>

      {/* Live Cover Preview Hero Banner */}
      <div
        ref={coverBannerRef}
        onMouseDown={(e) => {
          if ((e.target as HTMLElement).closest('button')) return;
          e.preventDefault();
          setIsDraggingCover(true);
          coverDragStartRef.current = {
            mouseX: e.clientX,
            mouseY: e.clientY,
            startPosX: coverPosX,
            startPosY: coverPosY,
          };
        }}
        className={`relative h-48 sm:h-56 w-full rounded-2xl overflow-hidden bg-slate-900 border border-slate-200/80 dark:border-[#333] shadow-md select-none group ${
          effectiveCoverUrl ? (isDraggingCover ? 'cursor-grabbing' : 'cursor-grab') : ''
        }`}
        title={effectiveCoverUrl ? 'Drag with mouse to reposition • Scroll wheel to zoom' : undefined}
      >
        {effectiveCoverUrl ? (
          // eslint-disable-next-line @next/next/no-img-element
          <img
            src={effectiveCoverUrl}
            alt="Deck Cover Preview"
            draggable={false}
            style={{
              objectPosition: `${coverPosX}% ${coverPosY}%`,
              transform: `scale(${coverZoom / 100})`,
            }}
            className="w-full h-full object-cover pointer-events-none select-none transition-transform duration-75"
          />
        ) : (
          <div className="w-full h-full flex flex-col items-center justify-center bg-slate-800 text-slate-400 gap-2">
            <ImageIcon className="w-8 h-8 opacity-40" />
            <span className="text-xs">Select or generate a cover</span>
          </div>
        )}

        <div className="absolute inset-0 bg-gradient-to-t from-black/85 via-black/30 to-black/20 pointer-events-none" />

        {/* Top-Right Badge */}
        <div className="absolute top-3.5 right-3.5 flex items-center gap-2 z-10">
          {coverMode === 'auto' && (
            <span className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full bg-black/60 backdrop-blur-md text-white text-[11px] font-medium border border-white/20 shadow-lg">
              <Sparkles className="w-3 h-3 text-amber-400" />
              <span>
                Auto Match: <strong className="text-amber-300 font-semibold">{aiDerivedTopic || targetLangName}</strong>
              </span>
            </span>
          )}

          {isSearchingCovers && (
            <span className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full bg-black/60 backdrop-blur-md text-slate-200 text-[10px] font-medium border border-white/10">
              <RefreshCw className="w-3 h-3 animate-spin text-accent-primary" />
              <span>Matching visual...</span>
            </span>
          )}

          {effectiveCoverUrl && (coverPosX !== 50 || coverPosY !== 50 || coverZoom !== 100) && (
            <button
              type="button"
              onClick={() => {
                setCoverPosX(50);
                setCoverPosY(50);
                setCoverZoom(100);
              }}
              className="px-2.5 py-1 rounded-full text-[11px] font-semibold bg-black/60 hover:bg-black/85 text-slate-200 hover:text-white backdrop-blur-md border border-white/20 transition cursor-pointer shadow-md"
              title="Reset position and zoom to center"
            >
              Reset
            </button>
          )}
        </div>

        {effectiveCoverUrl && (
          <div className="absolute top-3.5 left-3.5 z-10 pointer-events-none opacity-80 group-hover:opacity-100 transition-opacity">
            <span className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full bg-black/55 backdrop-blur-md text-white/90 text-[10px] font-medium border border-white/15 shadow-sm">
              <Move className="w-3 h-3 text-amber-400" />
              <span>Drag mouse to move &bull; Scroll to zoom ({coverZoom}%)</span>
            </span>
          </div>
        )}

        <div className="absolute bottom-3.5 left-3.5 right-3.5 flex items-end justify-between z-10 pointer-events-none">
          <div className="space-y-1 max-w-[80%] pointer-events-auto">
            {deckName.trim() && (
              <h3 className="text-base sm:text-lg font-black text-white drop-shadow-md truncate">
                {deckName.trim()}
              </h3>
            )}
            {description.trim() && (
              <p className="text-xs text-white/80 drop-shadow-sm line-clamp-1">
                {description.trim()}
              </p>
            )}
          </div>

          <button
            type="button"
            onClick={onRefreshAutoCover}
            title="Find another matching cover"
            className="pointer-events-auto px-3 py-1.5 rounded-full bg-white/90 hover:bg-white text-slate-900 text-xs font-bold shadow-md hover:scale-105 active:scale-95 transition-all flex items-center gap-1.5 cursor-pointer shrink-0"
          >
            <RefreshCw className={`w-3.5 h-3.5 ${isSearchingCovers ? 'animate-spin' : ''}`} />
            <span className="hidden sm:inline">Refresh Cover</span>
          </button>
        </div>
      </div>

      {/* Mode 1: Automatic */}
      {coverMode === 'auto' && (
        <div className="space-y-3 pt-1">
          <div className="flex items-center justify-between">
            <span className="text-xs font-bold text-slate-700 dark:text-slate-300 flex items-center gap-1.5">
              <Sparkles className="w-3.5 h-3.5 text-accent-primary" />
              Auto-Discovered for &ldquo;{aiDerivedTopic || targetLangName}&rdquo;
            </span>
            <span className="text-[11px] text-slate-400">Tap any photo to lock it as your cover</span>
          </div>

          <div className="grid grid-cols-2 sm:grid-cols-3 md:grid-cols-6 gap-2.5">
            {suggestedCovers.slice(0, 6).map((item) => {
              const isSelected = effectiveCoverUrl === item.url;
              return (
                <button
                  key={item.id}
                  type="button"
                  onClick={() => setSelectedCoverImage(item.url)}
                  className={`group relative h-20 sm:h-22 rounded-xl overflow-hidden border-2 transition-all cursor-pointer ${
                    isSelected
                      ? 'border-accent-primary ring-2 ring-accent-primary/40 scale-[1.02] shadow-sm'
                      : 'border-transparent hover:border-slate-300 dark:hover:border-slate-600 opacity-80 hover:opacity-100'
                  }`}
                >
                  {/* eslint-disable-next-line @next/next/no-img-element */}
                  <img
                    src={item.url}
                    alt={item.title}
                    className="w-full h-full object-cover group-hover:scale-110 transition-transform duration-300"
                  />
                  <div className="absolute inset-0 bg-gradient-to-t from-black/60 to-transparent" />
                  {isSelected && (
                    <div className="absolute top-1.5 right-1.5 w-5 h-5 rounded-full bg-accent-primary text-white flex items-center justify-center shadow-xs">
                      <Check className="w-3 h-3 stroke-[3]" />
                    </div>
                  )}
                  <span className="absolute bottom-1 left-1.5 right-1.5 text-[9.5px] font-medium text-white truncate text-left drop-shadow-sm">
                    {item.title}
                  </span>
                </button>
              );
            })}
          </div>
        </div>
      )}

      {/* Mode 2: Search */}
      {coverMode === 'search' && (
        <div className="space-y-4 pt-1">
          <div className="space-y-1.5">
            <div className="flex items-center justify-between">
              <label className="text-xs font-bold text-slate-700 dark:text-slate-300 block">
                Search Visual Photos
              </label>
              <span className="text-[10px] text-slate-400">Powered by Pexels</span>
            </div>
            <div className="relative flex items-center">
              <Search className="w-4 h-4 text-slate-400 absolute left-3.5 pointer-events-none" />
              <input
                type="text"
                value={coverSearchQuery}
                onChange={(e) => setCoverSearchQuery(e.target.value)}
                onKeyDown={(e) => {
                  if (e.key === 'Enter') {
                    e.preventDefault();
                    handleSearchManualCovers(coverSearchQuery);
                  }
                }}
                placeholder="Search any theme, city, culture, anime, nature, food..."
                className="w-full pl-10 pr-24 py-3 rounded-2xl bg-white dark:bg-[#282828] border border-slate-200/80 dark:border-[#383838] text-xs sm:text-sm font-normal text-slate-800 dark:text-slate-100 placeholder:text-slate-400 focus:outline-none focus:border-accent-primary dark:focus:border-slate-500 transition-colors shadow-2xs"
              />
              <button
                type="button"
                onClick={() => handleSearchManualCovers(coverSearchQuery)}
                disabled={isSearchingManual || !coverSearchQuery.trim()}
                className="absolute right-2 px-3.5 py-1.5 rounded-xl bg-accent-primary text-white text-xs font-bold hover:opacity-90 disabled:opacity-40 transition-all cursor-pointer flex items-center gap-1.5 shadow-xs"
              >
                {isSearchingManual ? (
                  <RefreshCw className="w-3.5 h-3.5 animate-spin" />
                ) : (
                  <Search className="w-3.5 h-3.5" />
                )}
                <span>Search</span>
              </button>
            </div>
          </div>

          <div className="flex items-center gap-1.5 flex-wrap">
            <span className="text-[10.5px] font-medium text-slate-400">Popular:</span>
            {[targetLangName, 'Landscape', 'Architecture', 'Culture', 'Tokyo', 'Coffee', 'Books', 'Nature'].map(
              (chip) => (
                <button
                  key={chip}
                  type="button"
                  onClick={() => {
                    setCoverSearchQuery(chip);
                    handleSearchManualCovers(chip);
                  }}
                  className="px-2.5 py-0.5 rounded-full text-[11px] font-medium bg-slate-100 dark:bg-white/5 hover:bg-slate-200 dark:hover:bg-white/10 text-slate-600 dark:text-slate-300 transition-colors cursor-pointer border border-transparent hover:border-slate-200 dark:hover:border-white/10"
                >
                  {chip}
                </button>
              )
            )}
          </div>

          {isSearchingManual ? (
            <div className="py-12 flex flex-col items-center justify-center gap-2 text-slate-400">
              <div className="w-6 h-6 border-2 border-accent-primary border-t-transparent rounded-full animate-spin" />
              <span className="text-xs">Finding high-resolution covers...</span>
            </div>
          ) : searchResults.length > 0 ? (
            <div className="grid grid-cols-2 sm:grid-cols-3 md:grid-cols-4 gap-3">
              {searchResults.map((item) => {
                const isSelected = effectiveCoverUrl === item.url;
                return (
                  <button
                    key={item.id}
                    type="button"
                    onClick={() => setSelectedCoverImage(item.url)}
                    className={`group relative h-28 rounded-xl overflow-hidden border-2 transition-all cursor-pointer ${
                      isSelected
                        ? 'border-accent-primary ring-2 ring-accent-primary/40 scale-[1.02] shadow-md'
                        : 'border-slate-200/60 dark:border-[#2f2f2f] hover:border-slate-300 dark:hover:border-slate-600 opacity-90 hover:opacity-100'
                    }`}
                  >
                    {/* eslint-disable-next-line @next/next/no-img-element */}
                    <img
                      src={item.url}
                      alt={item.title}
                      className="w-full h-full object-cover group-hover:scale-110 transition-transform duration-300"
                    />
                    <div className="absolute inset-0 bg-gradient-to-t from-black/70 via-black/20 to-transparent" />
                    {isSelected && (
                      <div className="absolute top-2 right-2 w-5 h-5 rounded-full bg-accent-primary text-white flex items-center justify-center shadow-xs">
                        <Check className="w-3 h-3 stroke-[3]" />
                      </div>
                    )}
                    <div className="absolute bottom-1.5 left-2 right-2 text-left">
                      <span className="text-[11px] font-bold text-white block drop-shadow-sm truncate">
                        {item.title}
                      </span>
                      {item.photographer && (
                        <span className="text-[9.5px] text-white/70 block truncate">By {item.photographer}</span>
                      )}
                    </div>
                  </button>
                );
              })}
            </div>
          ) : null}
        </div>
      )}

      {/* Mode 3: Presets */}
      {coverMode === 'presets' && (
        <div className="space-y-3 pt-1">
          <div className="flex items-center justify-between">
            <span className="text-xs font-bold text-slate-700 dark:text-slate-300">
              Curated Culture &amp; Category Presets
            </span>
            <span className="text-[11px] text-slate-400">Select any aesthetic style</span>
          </div>

          <div className="grid grid-cols-2 sm:grid-cols-3 md:grid-cols-5 gap-2.5">
            {CURATED_COVER_PRESETS.map((preset) => {
              const isSelected = effectiveCoverUrl === preset.url;
              return (
                <button
                  key={preset.id}
                  type="button"
                  onClick={() => setSelectedCoverImage(preset.url)}
                  className={`group relative h-24 rounded-xl overflow-hidden border-2 transition-all cursor-pointer ${
                    isSelected
                      ? 'border-accent-primary ring-2 ring-accent-primary/40 scale-[1.02] shadow-md'
                      : 'border-slate-200/60 dark:border-[#2f2f2f] hover:border-slate-300 dark:hover:border-slate-600 opacity-85 hover:opacity-100'
                  }`}
                >
                  {/* eslint-disable-next-line @next/next/no-img-element */}
                  <img
                    src={preset.url}
                    alt={preset.title}
                    className="w-full h-full object-cover group-hover:scale-110 transition-transform duration-300"
                  />
                  <div className="absolute inset-0 bg-gradient-to-t from-black/70 via-black/20 to-transparent" />
                  {isSelected && (
                    <div className="absolute top-1.5 right-1.5 w-5 h-5 rounded-full bg-accent-primary text-white flex items-center justify-center shadow-xs">
                      <Check className="w-3 h-3 stroke-[3]" />
                    </div>
                  )}
                  <div className="absolute bottom-1.5 left-2 right-2 text-left">
                    <span className="text-[11px] font-bold text-white block drop-shadow-sm truncate">
                      {preset.title}
                    </span>
                    <span className="text-[9.5px] text-white/70 block">
                      {preset.lang} &bull; {preset.category}
                    </span>
                  </div>
                </button>
              );
            })}
          </div>
        </div>
      )}

      {/* Mode 4: Custom URL */}
      {coverMode === 'custom' && (
        <div className="space-y-3 pt-1">
          <label className="text-xs font-bold text-slate-700 dark:text-slate-300 block">Custom Image URL</label>
          <div className="relative">
            <input
              type="url"
              value={customCoverInput}
              onChange={(e) => setCustomCoverInput(e.target.value)}
              placeholder="https://images.unsplash.com/... or your custom web image link"
              className="w-full px-4 py-3 rounded-2xl bg-white dark:bg-[#282828] border border-slate-200/80 dark:border-[#383838] text-xs sm:text-sm font-normal text-slate-800 dark:text-slate-100 placeholder:text-slate-400 focus:outline-none focus:border-accent-primary dark:focus:border-slate-500 transition-colors"
            />
            {customCoverInput && (
              <button
                type="button"
                onClick={() => setCustomCoverInput('')}
                className="absolute right-3.5 top-1/2 -translate-y-1/2 text-slate-400 hover:text-slate-600 dark:hover:text-white cursor-pointer"
              >
                <X className="w-4 h-4" />
              </button>
            )}
          </div>
          <p className="text-[11px] text-slate-400">
            Paste any high-resolution landscape photo URL (Unsplash, Pexels, Imgur, Wikimedia, etc.)
          </p>
        </div>
      )}
    </div>
  );
}
